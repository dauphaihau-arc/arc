#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const args = process.argv.slice(2);

function readOption(name, fallback) {
  const index = args.indexOf(name);

  return index >= 0 && args[index + 1] ? args[index + 1] : fallback;
}

const checkOnly = args.includes('--check');
const sourcePath = path.resolve(
  readOption('--tsv', path.join(repoRoot, 'apps/api/seed-data/auth-permissions.tsv')),
);
const outputPath = path.resolve(
  readOption(
    '--out',
    path.join(repoRoot, 'apps/web/packages/schemas/src/api/auth/permissions.generated.ts'),
  ),
);

function toMemberName(key) {
  const parts = key.split(/[^a-z0-9]+/i).filter(Boolean);

  if (parts.length === 0) {
    throw new Error(`Permission key "${key}" has no usable segments`);
  }

  return parts
    .map((part, index) => (index === 0
      ? part.charAt(0).toLowerCase() + part.slice(1)
      : part.charAt(0).toUpperCase() + part.slice(1)))
    .join('');
}

function readPermissionKeys(filePath) {
  const lines = readFileSync(filePath, 'utf8')
    .split(/\r?\n/)
    .map(line => line.trim())
    .filter(Boolean);

  if (lines.length === 0) {
    throw new Error(`${filePath} is empty`);
  }

  const [header, ...rows] = lines;

  if (!header.startsWith('key')) {
    throw new Error(`${filePath} must start with a "key" header row`);
  }

  const keys = rows.map((line) => {
    const [key] = line.split('\t');

    if (!key) {
      throw new Error(`${filePath}: row without a key: ${line}`);
    }

    if (!/^[a-z0-9]+(?:\.[a-z0-9_]+)+$/.test(key)) {
      throw new Error(`${filePath}: unexpected permission key "${key}"`);
    }

    return key;
  });

  const duplicates = keys.filter((key, index) => keys.indexOf(key) !== index);

  if (duplicates.length > 0) {
    throw new Error(`${filePath}: duplicate keys: ${[...new Set(duplicates)].join(', ')}`);
  }

  return [...keys].sort((left, right) => left.localeCompare(right));
}

function render(keys) {
  const members = keys.map((key) => {
    const member = toMemberName(key);

    return `  ${member}: '${key}',`;
  });
  const keyList = keys.map(key => `  '${key}',`);

  return [
    '// Generated by scripts/generate-permissions.mjs from apps/api/seed-data/auth-permissions.tsv.',
    '// Do not edit by hand; run `node scripts/generate-permissions.mjs` instead.',
    '',
    'export const PERMISSIONS = {',
    ...members,
    '} as const',
    '',
    'export const PERMISSION_KEYS = [',
    ...keyList,
    '] as const',
    '',
    'export type PermissionKey = (typeof PERMISSIONS)[keyof typeof PERMISSIONS]',
    '',
    'const PERMISSION_KEY_SET: ReadonlySet<string> = new Set(PERMISSION_KEYS)',
    '',
    'export function isPermissionKey(value: string): value is PermissionKey {',
    '  return PERMISSION_KEY_SET.has(value)',
    '}',
    '',
  ].join('\n');
}

const content = render(readPermissionKeys(sourcePath));

if (checkOnly) {
  let current = '';

  try {
    current = readFileSync(outputPath, 'utf8');
  }
  catch {
    console.error(`Missing generated file: ${outputPath}`);
    process.exit(1);
  }

  if (current !== content) {
    console.error(
      `Permission catalog drift: ${path.relative(repoRoot, outputPath)} is stale.\n`
      + 'Run `node scripts/generate-permissions.mjs` and commit the result.',
    );
    process.exit(1);
  }

  console.log('Permission catalog is up to date.');
  process.exit(0);
}

writeFileSync(outputPath, content);
console.log(`Wrote ${path.relative(repoRoot, outputPath)} (${readPermissionKeys(sourcePath).length} keys).`);
